class Instructor {
  final String id;
  final String name;
  final String title;
  final String bio;
  final String avatarUrl;
  final int totalCourses;
  final double rating;

  const Instructor({
    required this.id,
    required this.name,
    required this.title,
    required this.bio,
    required this.avatarUrl,
    required this.totalCourses,
    required this.rating,
  });
}
